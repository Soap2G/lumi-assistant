#!/usr/bin/env python3
"""Generate pi/ from config/ so the Pi coding agent can run with the Lumi
configuration (`lumi --pi`).

`config/` stays the untouched opencode source of truth. This script wipes
and regenerates `pi/` from it, so it is safe to re-run any time
`config/opencode.json`, `config/AGENTS.md` or `config/skills/` change.
Never hand-edit anything under `pi/` — it will be overwritten on the next
run.

Skills are not copied: `lumi-pi` passes `--skill <root>/config/skills`
and Pi discovers skills recursively.

Run from anywhere:

    python3 script/build_pi_package.py            # regenerate pi/
    python3 script/build_pi_package.py --check    # exit 1 if pi/ is stale
"""

import argparse
import json
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_SKILLS = REPO_ROOT / "config" / "skills"
SRC_OPENCODE_JSON = REPO_ROOT / "config" / "opencode.json"
SRC_AGENTS_MD = REPO_ROOT / "config" / "AGENTS.md"
OUT = REPO_ROOT / "pi"

SCHEMA_MODELS = "https://pi.dev/schemas/models.schema.json"

# Pi skill descriptions are documented as <= 1024 chars, but Pi does not
# enforce it (verified on pi-coding-agent 1.3.0: a 1500-char description is
# loaded in full, silently). Warn so the overlong ones are fixed (step 2).
MAX_DESCRIPTION = 1024

# Public MCP servers only. The rucio-* servers need OAuth and are added in
# a later step.
PUBLIC_MCP = {
    "atlasopenmagic": "ATLAS Open Data: releases, datasets, metadata, file URLs",
    "cernopendata": "CERN Open Data portal: records, files, search",
    "cerndocs": "Search and read CERN documentation sites (MkDocs and GitBook)",
}

# This marker is the opencode-specific part of AGENTS.md that Pi readers
# must know about. If the text changes, the note below must be reviewed.
OPENCODE_ONLY_MARKER = "opencode's `Read` tool returns binary bytes"

RUNTIME_NOTE = """

## Runtime: Pi

This session runs on the Pi coding agent, not opencode. Differences that
affect the guidelines above:

- MCP tools are named `mcp__<server>__<tool>` (for example
  `mcp__atlasopenmagic__<tool>`). Where the guidelines name an MCP server,
  use that server's tools.
- The PDF guideline above was written for opencode's `Read` tool. Keep
  following its recipe (`pdftotext`, then `pypdf`) unless you have
  confirmed that Pi's `Read` returns readable text for the file.
- Pi does not ask before it runs commands. The permission tables in the
  guidelines describe intent: ask the user before any command the
  guidelines mark as "ask", and never run commands marked "deny".
"""

GENERATED = "GENERATED by script/build_pi_package.py from config/ — do not hand-edit."


def extract_field(frontmatter: str, field: str) -> str:
    """Line-oriented, like config/evals/lint.py: descriptions contain ': '
    which is illegal in unquoted YAML scalars."""
    for line in frontmatter.splitlines():
        if line.startswith(f"{field}:"):
            return line[len(field) + 1 :].strip()
    raise ValueError(f"missing {field!r} field")


def load_opencode():
    return json.loads(SRC_OPENCODE_JSON.read_text())


def build_settings(config) -> dict:
    provider, _, model = config["model"].partition("/")
    if not model:
        raise ValueError(f"opencode.json `model` is not provider/id: {config['model']!r}")
    settings = {
        "defaultProvider": provider,
        "defaultModel": model,
        "enableInstallTelemetry": False,
        "defaultProjectTrust": "never",
        "enableSkillCommands": True,
    }
    # The schema of models.json has no provider timeout; Pi's equivalent is
    # a global setting. Carry the longest opencode provider timeout (aigw,
    # the default provider, sets 600000).
    timeouts = [
        p["options"]["timeout"]
        for p in config["provider"].values()
        if "timeout" in p.get("options", {})
    ]
    if timeouts:
        settings["retry"] = {"provider": {"timeoutMs": max(timeouts)}}
    return settings


def build_models(config) -> dict:
    providers = {}
    for name, prov in config["provider"].items():
        # Anthropic is built into Pi and reads ANTHROPIC_API_KEY.
        if prov.get("npm") != "@ai-sdk/openai-compatible":
            continue
        models = []
        for model_id, m in prov["models"].items():
            entry = {
                "id": model_id,
                "name": m["name"],
                "reasoning": m["reasoning"],
                "input": ["text", "image"] if m.get("attachment") else ["text"],
            }
            limit = m.get("limit", {})
            if "context" in limit:
                entry["contextWindow"] = limit["context"]
            if "output" in limit:
                entry["maxTokens"] = limit["output"]
            models.append(entry)
        providers[name] = {
            "name": prov["name"],
            "baseUrl": prov["options"]["baseURL"],
            "api": "openai-completions",
            "apiKey": f"${prov['env'][0]}",
            "models": models,
        }
    return {"$schema": SCHEMA_MODELS, "providers": providers}


def build_mcp(config) -> dict:
    servers = {}
    for name, description in PUBLIC_MCP.items():
        servers[name] = {"url": config["mcp"][name]["url"], "description": description}
    return {"mcpServers": servers}


def build_agents_md() -> str:
    text = SRC_AGENTS_MD.read_text()
    if OPENCODE_ONLY_MARKER not in text:
        raise ValueError(
            "AGENTS.md's opencode-specific PDF guideline has changed — review "
            "RUNTIME_NOTE and OPENCODE_ONLY_MARKER in this script"
        )
    return text.rstrip("\n") + "\n" + RUNTIME_NOTE


def long_descriptions():
    found = []
    for skill_md in sorted(SRC_SKILLS.rglob("SKILL.md")):
        text = skill_md.read_text()
        if not text.startswith("---\n"):
            continue
        frontmatter = text.split("\n---\n", 1)[0]
        description = extract_field(frontmatter, "description")
        if len(description) > MAX_DESCRIPTION:
            found.append((skill_md.parent.name, len(description)))
    return found


def dump(obj) -> str:
    return json.dumps(obj, indent=2) + "\n"


def generate(out: Path):
    config = load_opencode()
    out.mkdir(parents=True)
    files = {
        "settings.json": dump(build_settings(config)),
        "models.json": dump(build_models(config)),
        "mcp.json": dump(build_mcp(config)),
        "AGENTS.md": build_agents_md(),
        "README.md": (
            f"# lumi on Pi (generated)\n\n{GENERATED}\n\n"
            "Source of truth: `config/opencode.json`, `config/AGENTS.md`, "
            "`config/skills/`. Regenerate with "
            "`python3 script/build_pi_package.py`.\n"
        ),
    }
    for name, content in files.items():
        (out / name).write_text(content)


def tree(root: Path) -> dict:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if pi/ differs from the generated output")
    args = parser.parse_args()

    for name, size in long_descriptions():
        print(f"WARNING: skill {name!r} description is {size} chars (> {MAX_DESCRIPTION})", file=sys.stderr)

    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "pi"
            generate(fresh)
            if not OUT.exists() or tree(OUT) != tree(fresh):
                print("pi/ is out of date: run python3 script/build_pi_package.py", file=sys.stderr)
                return 1
        print("pi/ is up to date")
        return 0

    if OUT.exists():
        import shutil

        shutil.rmtree(OUT)
    generate(OUT)
    config = load_opencode()
    print(f"pi/ generated at {OUT}")
    print(f"  default model: {config['model']}")
    print(f"  providers:     {', '.join(build_models(config)['providers'])}")
    print(f"  mcp servers:   {', '.join(PUBLIC_MCP)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
